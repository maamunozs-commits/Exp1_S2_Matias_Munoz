CREATE TABLE roles (
    id NUMBER(19,0) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 100) PRIMARY KEY,
    nombre VARCHAR2(30 CHAR) NOT NULL UNIQUE,
    descripcion VARCHAR2(200 CHAR) NOT NULL
);
CREATE TABLE usuarios (
    id NUMBER(19,0) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 100) PRIMARY KEY,
    nombre VARCHAR2(100 CHAR) NOT NULL,
    correo VARCHAR2(150 CHAR) NOT NULL UNIQUE,
    contrasena_hash VARCHAR2(100 CHAR) NOT NULL,
    rol_id NUMBER(19,0) NOT NULL,
    fecha_creacion TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    CONSTRAINT fk_usuario_rol FOREIGN KEY (rol_id) REFERENCES roles(id)
);
CREATE INDEX idx_usuarios_rol ON usuarios(rol_id);
