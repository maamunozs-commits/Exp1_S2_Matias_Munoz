CREATE TABLE categorias (
    id NUMBER(19,0) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 100) PRIMARY KEY,
    nombre VARCHAR2(80 CHAR) NOT NULL UNIQUE,
    descripcion VARCHAR2(300 CHAR) NOT NULL
);
CREATE TABLE temas (
    id NUMBER(19,0) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 100) PRIMARY KEY,
    titulo VARCHAR2(180 CHAR) NOT NULL,
    contenido VARCHAR2(4000 CHAR) NOT NULL,
    categoria_id NUMBER(19,0) NOT NULL,
    autor_id NUMBER(19,0) NOT NULL,
    autor_nombre VARCHAR2(100 CHAR) NOT NULL,
    fecha_creacion TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    fecha_actualizacion TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    CONSTRAINT fk_tema_categoria FOREIGN KEY (categoria_id) REFERENCES categorias(id)
);
CREATE TABLE comentarios (
    id NUMBER(19,0) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 100) PRIMARY KEY,
    contenido VARCHAR2(2000 CHAR) NOT NULL,
    tema_id NUMBER(19,0) NOT NULL,
    autor_id NUMBER(19,0) NOT NULL,
    autor_nombre VARCHAR2(100 CHAR) NOT NULL,
    fecha_creacion TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    fecha_actualizacion TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    CONSTRAINT fk_comentario_tema FOREIGN KEY (tema_id) REFERENCES temas(id)
);
CREATE INDEX idx_temas_categoria ON temas(categoria_id);
CREATE INDEX idx_temas_autor ON temas(autor_id);
CREATE INDEX idx_comentarios_tema ON comentarios(tema_id);
