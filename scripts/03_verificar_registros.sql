SET LINESIZE 240 PAGESIZE 100 FEEDBACK OFF TAB OFF
COLUMN tabla FORMAT A15
COLUMN registros FORMAT 999999
COLUMN id FORMAT 999999
COLUMN tema_id FORMAT 999999
COLUMN nombre FORMAT A20
COLUMN correo FORMAT A30
COLUMN rol FORMAT A16
COLUMN titulo FORMAT A55
COLUMN categoria FORMAT A26
COLUMN autor_nombre FORMAT A20
COLUMN contenido FORMAT A80
SELECT 'ROLES' AS TABLA, COUNT(*) AS REGISTROS FROM MM_USUARIOS.ROLES
UNION ALL SELECT 'USUARIOS', COUNT(*) FROM MM_USUARIOS.USUARIOS
UNION ALL SELECT 'CATEGORIAS', COUNT(*) FROM MM_FORO.CATEGORIAS
UNION ALL SELECT 'TEMAS', COUNT(*) FROM MM_FORO.TEMAS
UNION ALL SELECT 'COMENTARIOS', COUNT(*) FROM MM_FORO.COMENTARIOS;
SELECT u.id, u.nombre, u.correo, r.nombre AS rol FROM MM_USUARIOS.usuarios u JOIN MM_USUARIOS.roles r ON r.id = u.rol_id ORDER BY u.id;
SELECT t.id, t.titulo, c.nombre AS categoria, t.autor_nombre FROM MM_FORO.temas t JOIN MM_FORO.categorias c ON c.id = t.categoria_id ORDER BY t.id;
SELECT id, tema_id, contenido, autor_nombre FROM MM_FORO.comentarios ORDER BY id;
